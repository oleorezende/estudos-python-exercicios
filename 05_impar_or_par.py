#Faça um programa que receba um número. 
# Verifique se o número informado é par ou ímpar. 
# Exiba o resultado da seguinte maneira:
# %%

numero = int(input("me fale um numero, vou ver se é par ou não"))

if numero % 2 == 0:
    print (numero,"é par")
else:
    print (numero, "é impar")
